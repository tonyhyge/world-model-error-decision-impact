"""The same CartPole diagnosis, moved onto the distribution the agent visits.

Experiment 2 scores a uniform box of states. That box is declared in advance
and is easy to audit, but it is not where a controller actually spends its
time, and the thesis lists this as a limitation. Here the identical ensemble
protocol is evaluated on held-out trajectories rolled out by the reference
policy instead.

The run also separates two kinds of score. The margin of the true reference is
*privileged*: computing it needs the very reference the model is supposed to
replace. The dispersion-over-margin score is *unprivileged*, using only
quantities a deployed agent already has. Only the second is deployable, so
they are reported apart.
"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import numpy as np
import torch
import gymnasium as gym
from experiments.common import SEEDS, write_csv
from experiments.exp2_cartpole_continuous import model_values
from src.envs.cartpole_continuous import CartPoleDynamics, CartPoleCompetentAgent
from src.models.ensemble_dynamics import MLPEnsembleDynamics

HOLDOUT_EPISODES = 20
# Offset keeps these resets disjoint from the collection and rollout seeds
# used by experiment 2.
HOLDOUT_SEED_OFFSET = 700
EPSILON_MARGIN = 1e-3


def dispersion(ensemble, state):
    """Ensemble spread over next-state predictions, averaged over actions."""
    spreads = []
    for action in (0, 1):
        _, variance = ensemble.predict(state, action)
        spreads.append(float(np.sqrt(np.sum(variance))))
    return float(np.mean(spreads))


def run():
    torch.set_num_threads(1)
    torch.use_deterministic_algorithms(True)
    dyn = CartPoleDynamics()
    agent = CartPoleCompetentAgent(dyn)
    rows = []
    for seed in SEEDS:
        torch.manual_seed(seed)
        rng = np.random.default_rng(seed)
        env = gym.make('CartPole-v1')
        # Identical collection and fitting protocol to experiment 2, so the two
        # evaluations differ only in where they are scored.
        data = []
        for ep in range(20):
            s, _ = env.reset(seed=seed * 1000 + ep)
            for _ in range(30):
                a = int(rng.integers(2)) if rng.random() < .2 else agent.select_action(s)
                ns, r, term, trunc, _ = env.step(a)
                data.append((s.copy(), a, ns.copy()))
                s = ns
                if term or trunc:
                    break
        states = np.array([d[0] for d in data])
        actions = np.array([d[1] for d in data])
        next_states = np.array([d[2] for d in data])
        ensemble = MLPEnsembleDynamics(num_models=5, hidden_dim=64)
        for _ in range(120):
            order = rng.permutation(len(data))
            for start in range(0, len(data), 32):
                ix = order[start:start + 32]
                ensemble.train_step(states[ix], actions[ix], next_states[ix])

        for episode in range(HOLDOUT_EPISODES):
            s, _ = env.reset(seed=seed * 1000 + HOLDOUT_SEED_OFFSET + episode)
            for step in range(500):
                q = agent.get_action_values(s)
                qhat, _ = model_values(ensemble, agent, s)
                reference_action = int(q[1] >= q[0])
                model_action = int(qhat[1] >= qhat[0])
                model_margin = float(abs(qhat[1] - qhat[0]))
                rows.append(dict(
                    seed=seed, episode=episode, step=step,
                    true_margin=float(abs(q[1] - q[0])),
                    model_margin=model_margin,
                    sigma_dyn=dispersion(ensemble, s),
                    # Unprivileged: dispersion scaled by how close the model
                    # thinks it is to its own decision boundary.
                    unprivileged_score=dispersion(ensemble, s) / (model_margin + EPSILON_MARGIN),
                    reference_action=reference_action, model_action=model_action,
                    decision_flip=int(reference_action != model_action)))
                # The trajectory is generated by the reference policy, so the
                # state pool does not depend on which model is being scored.
                s, _, term, trunc, _ = env.step(reference_action)
                if term or trunc:
                    break
        env.close()
        print(f'CartPole held-out seed {seed} complete', flush=True)
    write_csv('exp6_cartpole_holdout.csv', rows)


if __name__ == '__main__':
    run()
